ALTER TYPE "DocType" ADD VALUE IF NOT EXISTS 'LOCATION_NOTICE';
ALTER TYPE "DocType" ADD VALUE IF NOT EXISTS 'BIOMETRIC_NOTICE';
ALTER TYPE "DocType" ADD VALUE IF NOT EXISTS 'WORK_TIME_POLICY';
ALTER TYPE "DocType" ADD VALUE IF NOT EXISTS 'AI_USAGE_POLICY';
ALTER TYPE "DocType" ADD VALUE IF NOT EXISTS 'DATA_RETENTION_POLICY';
ALTER TYPE "DocType" ADD VALUE IF NOT EXISTS 'SUBPROCESSORS_LIST';
